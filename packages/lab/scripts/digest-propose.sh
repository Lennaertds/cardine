#!/usr/bin/env bash
# Builds a proposal Markdown from recent digest dumps. Never changes radar.md (P5).
# DIGEST_DRY_RUN=1 — show the path without writing.
# DIGEST_PROPOSE_FROM=<dir> — that dump folder only (default: newest under data/external/digest/).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
TODAY="$(date +%F)"
DUMP_ROOT="data/external/digest"
PROP_DIR="docs/research/digest/proposals"
OUT="$PROP_DIR/${TODAY}-draft.md"
MAX_ITEMS="${DIGEST_PROPOSE_LIMIT:-15}"

die() { echo "digest-propose: $*" >&2; exit 1; }
tip() { echo "digest-propose: $*" >&2; }

[[ -f docs/research/digest/README.md ]] || die "ontbreekt docs/research/digest/ (kit: --modules research)."
[[ -d "$DUMP_ROOT" ]] || die "no $DUMP_ROOT — run make digest-fetch first"

pick_dumps() {
  if [[ -n "${DIGEST_PROPOSE_FROM:-}" ]]; then
    [[ -d "$DIGEST_PROPOSE_FROM" ]] || die "DIGEST_PROPOSE_FROM is not a folder: $DIGEST_PROPOSE_FROM"
    printf '%s\n' "$DIGEST_PROPOSE_FROM"
    return
  fi
  # Nieuwste dump-mappen (datum-prefix), max 5
  find "$DUMP_ROOT" -mindepth 1 -maxdepth 1 -type d ! -name '.*' \
    | sort -r | head -n 5
}

mapfile -t DUMPS < <(pick_dumps)
[[ ${#DUMPS[@]} -gt 0 ]] || die "no dump folders in $DUMP_ROOT — run make digest-fetch first"

if [[ "${1:-}" == "--dry-run" ]] || [[ "${DIGEST_DRY_RUN:-}" == "1" ]]; then
  tip "dry-run — zou voorstel schrijven naar $OUT uit:"
  for d in "${DUMPS[@]}"; do echo "  - $d"; done
  echo "digest-propose: dry-run klaar"
  exit 0
fi

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
candidates="$tmpdir/rows.md"
: >"$candidates"
count=0

for d in "${DUMPS[@]}"; do
  items="$d/items.md"
  src=""
  [[ -f "$d/source.txt" ]] && src="$(tr -d '\r' <"$d/source.txt" | head -n1)"
  [[ -f "$items" ]] || { tip "no items.md in $d — skipped"; continue; }
  # Tabelrijen na header (skip tot eerste | Titel of na tweede |---|)
  while IFS= read -r line; do
    [[ "$line" == \|* ]] || continue
    [[ "$line" =~ Tit[e]?l ]] && continue
    [[ "$line" =~ ^\|[-:[:space:]\|]+\|$ ]] && continue
    # | title | link |
    title="$(printf '%s' "$line" | awk -F'|' '{gsub(/^ +| +$/,"",$2); print $2}')"
    link="$(printf '%s' "$line" | awk -F'|' '{gsub(/^ +| +$/,"",$3); print $3}')"
    [[ -n "$title" ]] || continue
    [[ "$title" != "—" ]] || continue
    printf '| Assess | tooling | %s | digest candidate — curate; source %s · %s |\n' \
      "$title" "${src:-$d}" "${link:-—}" >>"$candidates"
    count=$((count + 1))
    [[ "$count" -ge "$MAX_ITEMS" ]] && break 2
  done <"$items"
done

[[ "$count" -gt 0 ]] || die "no items to propose (empty items.md?)"

mkdir -p "$PROP_DIR"
{
  echo "# Digest proposal — $TODAY"
  echo
  echo "> **Not SSOT.** Generated by \`make digest-propose\`. Copy accepted rows by hand into [radar.md](../../radar.md) (Trial/Assess) or the wantlist. Merging a draft PR = the proposal is in, not auto-radar (P5)."
  echo
  echo "## Candidate rows"
  echo
  echo "| Ring | Category | Item | Note / ADR |"
  echo "|------|----------|------|--------------|"
  cat "$candidates"
  echo
  echo "## Checklist"
  echo
  echo "- [ ] Irrelevant rows removed"
  echo "- [ ] Ring updated (Assess → Trial only with intent)"
  echo "- [ ] Accepted → pasted into \`radar.md\`; the dump stays in \`data/external/digest/\`"
  echo "- [ ] Agent Engineering repo: \`bron/bronnen.md\` § first, then the bridge"
} >"$OUT"

tip "written: $OUT ($count candidates)"
echo "digest-propose: done — review $OUT; open a draft PR if needed (team: .github/workflows/digest.yml)"
